"""Generate the progress report's two result tables (report/main.tex) from the committed seed CSVs.

The tables used to be typed by hand. This script writes them from the data, so the report cannot disagree
with results/. It reads ONLY committed CSVs (no cluster, no GPU, no per-problem files):

  results/seeds_by_set.csv            method x split x metric (n_seeds, mean, sd): test_hard pass@1, pass@128,
                                      newly_solved
  results/seeds_hard_levels.csv       the level == "18-20" rows: newly_solved_mean / newly_solved_sd
  results/seeds_gradient_budget.csv   informative_frac_mean: share of all GRPO groups with nonzero gradient

Outputs (LaTeX fragments holding only the tabular environment; table, caption and label stay in main.tex,
which pulls them in with \\input{tables/...}):

  report/tables/main_results.tex     Table tab:main  - one row per arm, ordered as in ARMS below
  report/tables/decomposition.tex    Table tab:decomp - tau=0.1's gain over the fixed band in newly solved
                                     problems (hard set and op 18-20), split into three steps:
                                       harder problems  uniform        - fixed_band
                                       right range      uniform_11_17  - uniform
                                       schedule         threshold_tau1 - uniform_11_17
                                     each with its share of threshold_tau1 - fixed_band (whole percent).

Formatting: "$mean\\pm sd$" to one decimal; an arm with one seed has no sd and prints the bare value (and a
newly-solved count as an integer). Rounding is Python's float formatting, the same as the scripts that wrote
the docs; it decides values that sit on a .x5 boundary in the CSV (e.g. 0.2865 -> 28.6%).

    $EDGE_PY eval/report_tables.py [--results-dir results] [--out-dir report/tables]
After regenerating, rebuild the PDF: sbatch --wait report/build.sbatch
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from runs_io import REPO  # noqa: E402

# (method, row label, bold). Order and labels follow the report; the macros \tauone etc. live in main.tex.
ARMS = [
    ("threshold_tau1", r"threshold \tauone\ (headroom)", True),
    ("uniform_11_17", r"control: uniform op 11--17", False),
    ("uniform", r"uniform op 2--20", False),
    ("fixed_band", r"fixed band op 11--14 (paper)", False),
    ("threshold_tau3", r"threshold \tauthree", False),
    ("bandit", r"bandit, $m=25$ (learning speed)", False),
    ("threshold_tau5", r"threshold \taufive\ (gradient eff.)", False),
]
# (label, minuend, subtrahend) for the decomposition; the three steps telescope to tau1 - fixed_band.
STEPS = [
    (r"harder problems\textsuperscript{a}", "uniform", "fixed_band"),
    (r"right range\textsuperscript{b}", "uniform_11_17", "uniform"),
    (r"schedule\textsuperscript{c}", "threshold_tau1", "uniform_11_17"),
]
TOTAL = ("threshold_tau1", "fixed_band")
HEADER = "% Generated by eval/report_tables.py from results/seeds_*.csv. Do not edit by hand; rerun the script.\n"


def _num(s: str) -> float | None:
    """CSV cell -> float; an empty cell (sd of a single-seed arm) -> None."""
    return float(s) if s.strip() else None


def _read(path: Path) -> list[dict]:
    with Path(path).open(newline="") as fh:
        return list(csv.DictReader(fh))


def load(results_dir: Path) -> dict[str, dict]:
    """Per method: n_seeds and (mean, sd) for every number the tables need. Missing data raises, never blanks."""
    out: dict[str, dict] = {}
    for r in _read(results_dir / "seeds_by_set.csv"):
        if r["split"] == "test_hard" and r["metric"] in ("pass@1", "pass@128", "newly_solved"):
            d = out.setdefault(r["method"], {})
            d["n_seeds"] = int(r["n_seeds"])
            d[r["metric"]] = (float(r["mean"]), _num(r["sd"]))
    for r in _read(results_dir / "seeds_hard_levels.csv"):
        if r["level"] == "18-20" and r["method"] in out:
            out[r["method"]]["new_18_20"] = (float(r["newly_solved_mean"]), _num(r["newly_solved_sd"]))
    for r in _read(results_dir / "seeds_gradient_budget.csv"):
        if r["method"] in out:
            out[r["method"]]["informative"] = float(r["informative_frac_mean"])
    need = ("pass@1", "pass@128", "newly_solved", "new_18_20", "informative")
    for method, _, _ in ARMS:
        missing = [k for k in need if k not in out.get(method, {})]
        if missing:
            raise KeyError(f"{method}: no {missing} in {results_dir}")
    return out


def cell(mean: float, sd: float | None, n_seeds: int, bold: bool = False, count: bool = False) -> str:
    """'$22.8\\pm0.2$' / '$\\mathbf{22.8\\pm0.2}$'; single seed -> '0.0', or '0' for a count."""
    if n_seeds == 1 or sd is None:
        return f"{mean:.0f}" if count and float(mean).is_integer() else f"{mean:.1f}"
    body = f"{mean:.1f}\\pm{sd:.1f}"
    return f"$\\mathbf{{{body}}}$" if bold else f"${body}$"


def _rows(cells: list[list[str]]) -> str:
    """Join cells into tabular rows, padding columns so the generated .tex stays readable."""
    widths = [max(len(c[i]) for c in cells) for i in range(len(cells[0]) - 1)]
    lines = []
    for c in cells:
        lines.append(" & ".join([x.ljust(w) for x, w in zip(c[:-1], widths)] + [c[-1]]) + r" \\")
    return "\n".join(lines) + "\n"


def main_table(data: dict[str, dict]) -> str:
    body = []
    for method, label, bold in ARMS:
        d, n = data[method], data[method]["n_seeds"]
        body.append([label, str(n),
                     cell(*d["pass@1"], n, bold), cell(*d["pass@128"], n, bold),
                     cell(*d["newly_solved"], n, bold, count=True), cell(*d["new_18_20"], n, bold, count=True),
                     f"{100 * d['informative']:.1f}\\%"])
    return (HEADER + "\\begin{tabular}{lcccccc}\n\\toprule\n"
            "& & \\multicolumn{3}{c}{hard set, op 15--20} & op 18--20 & informative \\\\\n"
            "\\cmidrule(lr){3-5}\n"
            "arm & seeds & pass@1 & pass@128 & \\textbf{new} (/204) & \\textbf{new} (/102) & groups \\\\\n"
            "\\midrule\n" + _rows(body) + "\\bottomrule\n\\end{tabular}\n")


def decomposition(data: dict[str, dict]) -> tuple[str, dict]:
    """The tabular, plus the raw differences {(column, step label): (delta, share)} for checks and tests."""
    cols = {"hard": "newly_solved", "18-20": "new_18_20"}
    total = {c: data[TOTAL[0]][k][0] - data[TOTAL[1]][k][0] for c, k in cols.items()}
    parts, body = {}, []
    for label, a, b in STEPS:
        row = [label]
        for c, k in cols.items():
            delta = data[a][k][0] - data[b][k][0]
            share = 100 * delta / total[c] if total[c] else math.nan
            parts[(c, label)] = (delta, share)
            row.append(f"${delta:+.1f}$ ({share:.0f}\\%)")
        body.append(row)
    text = (HEADER + "\\begin{tabular}{lcc}\n\\toprule\n"
            f"step & hard (${total['hard']:+.1f}$) & op 18--20 (${total['18-20']:+.1f}$) \\\\\n"
            "\\midrule\n" + _rows(body) + "\\bottomrule\n\\end{tabular}\n")
    return text, parts


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--results-dir", type=Path, default=REPO / "results")
    ap.add_argument("--out-dir", type=Path, default=REPO / "report" / "tables")
    args = ap.parse_args()

    data = load(args.results_dir)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "main_results.tex").write_text(main_table(data), encoding="utf-8")
    decomp, parts = decomposition(data)
    (args.out_dir / "decomposition.tex").write_text(decomp, encoding="utf-8")
    shares = {c: sum(s for (cc, _), (_, s) in parts.items() if cc == c) for c in ("hard", "18-20")}
    print(f"wrote {args.out_dir / 'main_results.tex'} and {args.out_dir / 'decomposition.tex'}; "
          f"decomposition shares sum to {shares['hard']:.1f}% (hard), {shares['18-20']:.1f}% (op 18-20)")


if __name__ == "__main__":
    main()
